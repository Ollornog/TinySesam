def select(raw: bytes) -> list[str]:
    out, seen = [], set()
    for line in raw.splitlines():
        z = line.decode("utf-8", "replace").strip().lower()
        if not MIN_LENGTH <= len(z) <= MAX_LENGTH or "�" in z or z.startswith("#"):
            continue
        if any(c < " " or c == "\x7f" for c in z) or z in seen:
            continue
        seen.add(z)
        out.append(z)
        if len(out) == ENTRIES:
            break
    if len(out) < ENTRIES:
        raise SystemExit(f"only {len(out)} entries qualify, {ENTRIES} wanted")
    return out


def build() -> str:
    with urllib.request.urlopen(URL, timeout=60) as r:   # noqa: S310 — fixed https address
        raw = r.read()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SHA256:
        raise SystemExit(f"source changed: sha256 {digest}, expected {SHA256}")
    return HEADER + "\n".join(select(raw)) + "\n"


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        same = DESTINATION.read_text(encoding="utf-8") == text
        print("up to date" if same else f"{DESTINATION.name} differs from a fresh build")
        return 0 if same else 1
    DESTINATION.write_text(text, encoding="utf-8")
    print(f"wrote {DESTINATION.relative_to(ROOT)} ({ENTRIES} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
