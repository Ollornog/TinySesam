#!/usr/bin/env python3
"""Generates CONFIGURATION.md from tinysesam/config.py.

Why generated: Of 119 fields, 39 appeared in no README — maintaining a reference by hand
means it is incomplete again at the next new field. Here the code is the source, and a check
in the hygiene test keeps the two together (as with the backlog index).

    python3 scripts/_config_docs.py              # write
    python3 scripts/_config_docs.py --dry-run    # check only (exit 1 = outdated)

What is harvested: the section headings (`# --- … ---`), the comment behind a field and,
if there is none, the comment lines directly above it.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tinysesam" / "config.py"
DESTINATION = ROOT / "CONFIGURATION.md"
#: The tier of each field (since 0.22.0) lives with the guard of the public surface.
STORAGE = ROOT / "tests" / "api_surface.json"

HEAD = """# Configuration — all fields of `TinySesamConfig`

<!-- GENERATED by scripts/_config_docs.py — do not maintain by hand.
     Rebuild: `python3 scripts/_config_docs.py` -->

The source is `tinysesam/config.py`; this page is its extract. What a field *means* is written
there as a comment — here in the same order, grouped by topic.

The READMEs explain the **paths** (which method for what, how to combine them). This
reference answers the other question: *"There is a field — what does it do?"*

Presets (`TinySesamConfig.local_accounts()`, `.oidc_gateway()`, …) set bundles of these fields;
individual ones can be overridden via `**overrides`.

"""


def tiers() -> dict:
    """{field: tier} from `tests/api_surface.json` — empty if the file does not exist."""
    if not STORAGE.exists():
        return {}
    fields = json.loads(STORAGE.read_text(encoding="utf-8")).get("TinySesamConfig.fields", {})
    return {n: e.get("tier") for n, e in fields.items() if isinstance(e, dict)}


def fields():
    """(section, name, type, default, description) in source order."""
    text = SOURCE.read_text(encoding="utf-8")
    # Only the class body up to the first method.
    body = text[text.index("class TinySesamConfig"):]
    cut = re.search(r"\n    @|\n    def ", body)
    if cut:
        body = body[:cut.start()]

    section = "General"
    before: list[str] = []
    result: list[list[str]] = []
    # Was the previous line a field WITH a comment behind it? Then an indented comment line
    # directly below belongs to THIS field (continuation), not to the next one (B3-15).
    # Before, e.g. "warn = also runs WITHOUT a certificate" from `https_mode` ended up in the
    # description of `login_identifier` — a security-relevant field with someone else's text.
    continuation = False
    for line in body.splitlines():
        blank = line.strip()
        head = re.match(r"^#\s*---\s*(.+?)\s*---\s*$", blank)
        if head:
            section, before, continuation = head.group(1), [], False
            continue
        if blank.startswith("#"):
            # `#:` is the doc-comment form; the colon does not belong in the text.
            text = blank.lstrip("#").lstrip(":").strip()
            indentation = len(line) - len(line.lstrip())
            if continuation and indentation > 4:
                result[-1][4] = (result[-1][4] + " " + text).strip()
            else:
                continuation = False
                before.append(text)
            continue
        continuation = False
        slot = re.match(r"^\s{4}([a-z_][a-z0-9_]*)\s*:\s*([^=]+?)\s*=\s*(.+?)\s*(?:#\s*(.*))?$", line)
        if not slot:
            if blank:
                before = []
            continue
        name, type_name, default, behind = slot.groups()
        description = (behind or " ".join(t for t in before if t)).strip()
        continuation = bool(behind)
        before = []
        result.append([section, name, type_name.strip(), default.strip(), description])
    for entry in result:
        yield tuple(entry)


def build() -> str:
    all_items = list(fields())
    # A section with exactly ONE field is really the description of that field —
    # `# --- Language of the built-in texts (en|de; …) ---` above `lang: str = "en"`, say. Without
    # this step 35 fields would show a "—", and nobody looks up a reference
    # that stays silent on every third entry a second time.
    per_section: dict = {}
    for section, *_ in all_items:
        per_section[section] = per_section.get(section, 0) + 1

    # The tier (PO decision 2026-09-26): Almost every field is A. Only what deviates from that
    # is marked — in the meaning column, so the line still begins with "| `name` |".
    tier = tiers()
    deviating = sorted(n for _, n, *_ in all_items if tier.get(n) != "A")
    parts = [HEAD, "**Tier:** Every field belongs to tier A — public, stable from 1.0 (see "
                   "[API.md](API.md), “Three tiers”)"
             + ("" if not deviating else
                ", except " + ", ".join(f"`{n}` ({tier.get(n) or 'no tier'})"
                                        for n in deviating))
             + ".\n"]
    current = None
    for section, name, type_name, default, description in all_items:
        if not description and per_section[section] == 1:
            description = section
        if section != current:
            current = section
            parts.append(f"\n## {section}\n\n| Field | Type | Default | Meaning |\n|---|---|---|---|\n")
        prior = default.replace("field(default_factory=lambda: ", "").replace("field(default_factory=", "")
        prior = prior.rstrip(")") if prior.endswith(")") and "(" not in prior[:-1] else prior
        text = description.replace("|", "\\|") or "—"
        if tier.get(name) != "A" and text != "—":
            text = f"**Tier {tier.get(name) or '?'}.** {text}"
        parts.append(f"| `{name}` | `{type_name}` | `{prior}` | {text} |\n")
    number = len(all_items)
    parts.append(f"\n---\n\n{number} fields, generated from `tinysesam/config.py`.\n")
    return "".join(parts)


def main() -> int:
    new = build()
    dry = "--dry-run" in sys.argv
    old = DESTINATION.read_text(encoding="utf-8") if DESTINATION.exists() else ""
    if dry:
        if old != new:
            print(f"{DESTINATION.name} is out of date — run `python3 scripts/_config_docs.py`",
                  file=sys.stderr)
            return 1
        return 0
    DESTINATION.write_text(new, encoding="utf-8")
    print(f"written: {DESTINATION.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
