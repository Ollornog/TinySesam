#!/usr/bin/env python3
"""Generates CONFIGURATION.md from tinysesam/config.py.

Why generated: Of 119 fields, 39 appeared in no README — maintaining a reference by hand
means it is incomplete again at the next new field. Here the code is the source, and a check
in the hygiene test keeps the two together (as with the backlog index).

    python3 scripts/_config_docs.py              # write
    python3 scripts/_config_docs.py --dry-run    # check only (exit 1 = outdated)

What is harvested: the section headings (`# --- … ---`), the comment behind a field and,
if there is none, the comment lines directly above it.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
QUELLE = ROOT / "tinysesam" / "config.py"
ZIEL = ROOT / "CONFIGURATION.md"
#: The tier of each field (since 0.22.0) lives with the guard of the public surface.
ABLAGE = ROOT / "tests" / "api_surface.json"

KOPF = """# Configuration — all fields of `TinySesamConfig`

<!-- GENERATED by scripts/_config_docs.py — do not maintain by hand.
     Rebuild: `python3 scripts/_config_docs.py` -->

The source is `tinysesam/config.py`; this page is its extract. What a field *means* is written
there as a comment — here in the same order, grouped by topic.

The READMEs explain the **paths** (which method for what, how to combine them). This
reference answers the other question: *"There is a field — what does it do?"*

Presets (`TinySesamConfig.local_accounts()`, `.oidc_gateway()`, …) set bundles of these fields;
individual ones can be overridden via `**overrides`.

"""


def stufen() -> dict:
    """{field: tier} from `tests/api_surface.json` — empty if the file does not exist."""
    if not ABLAGE.exists():
        return {}
    felder = json.loads(ABLAGE.read_text(encoding="utf-8")).get("TinySesamConfig.felder", {})
    return {n: e.get("stufe") for n, e in felder.items() if isinstance(e, dict)}


def felder():
    """(section, name, type, default, description) in source order."""
    text = QUELLE.read_text(encoding="utf-8")
    # Only the class body up to the first method.
    rumpf = text[text.index("class TinySesamConfig"):]
    schnitt = re.search(r"\n    @|\n    def ", rumpf)
    if schnitt:
        rumpf = rumpf[:schnitt.start()]

    abschnitt = "General"
    davor: list[str] = []
    ergebnis: list[list[str]] = []
    # Was the previous line a field WITH a comment behind it? Then an indented comment line
    # directly below belongs to THIS field (continuation), not to the next one (B3-15).
    # Before, e.g. "warn = also runs WITHOUT a certificate" from `https_mode` ended up in the
    # description of `login_identifier` — a security-relevant field with someone else's text.
    fortsetzung = False
    for zeile in rumpf.splitlines():
        blank = zeile.strip()
        kopf = re.match(r"^#\s*---\s*(.+?)\s*---\s*$", blank)
        if kopf:
            abschnitt, davor, fortsetzung = kopf.group(1), [], False
            continue
        if blank.startswith("#"):
            # `#:` is the doc-comment form; the colon does not belong in the text.
            text = blank.lstrip("#").lstrip(":").strip()
            einrueckung = len(zeile) - len(zeile.lstrip())
            if fortsetzung and einrueckung > 4:
                ergebnis[-1][4] = (ergebnis[-1][4] + " " + text).strip()
            else:
                fortsetzung = False
                davor.append(text)
            continue
        fortsetzung = False
        feld = re.match(r"^\s{4}([a-z_][a-z0-9_]*)\s*:\s*([^=]+?)\s*=\s*(.+?)\s*(?:#\s*(.*))?$", zeile)
        if not feld:
            if blank:
                davor = []
            continue
        name, typ, vorgabe, hinter = feld.groups()
        beschreibung = (hinter or " ".join(t for t in davor if t)).strip()
        fortsetzung = bool(hinter)
        davor = []
        ergebnis.append([abschnitt, name, typ.strip(), vorgabe.strip(), beschreibung])
    for eintrag in ergebnis:
        yield tuple(eintrag)


def bauen() -> str:
    alle = list(felder())
    # A section with exactly ONE field is really the description of that field —
    # `# --- Language of the built-in texts (en|de; …) ---` above `lang: str = "en"`, say. Without
    # this step 35 fields would show a "—", and nobody looks up a reference
    # that stays silent on every third entry a second time.
    je_abschnitt: dict = {}
    for abschnitt, *_ in alle:
        je_abschnitt[abschnitt] = je_abschnitt.get(abschnitt, 0) + 1

    # The tier (PO decision 2026-09-26): Almost every field is A. Only what deviates from that
    # is marked — in the meaning column, so the line still begins with "| `name` |".
    stufe = stufen()
    abweichend = sorted(n for _, n, *_ in alle if stufe.get(n) != "A")
    teile = [KOPF, "**Tier:** Every field belongs to tier A — public, stable from 1.0 (see "
                   "[API.md](API.md), “Three tiers”)"
             + ("" if not abweichend else
                ", except " + ", ".join(f"`{n}` ({stufe.get(n) or 'no tier'})"
                                        for n in abweichend))
             + ".\n"]
    aktuell = None
    for abschnitt, name, typ, vorgabe, beschreibung in alle:
        if not beschreibung and je_abschnitt[abschnitt] == 1:
            beschreibung = abschnitt
        if abschnitt != aktuell:
            aktuell = abschnitt
            teile.append(f"\n## {abschnitt}\n\n| Field | Type | Default | Meaning |\n|---|---|---|---|\n")
        vor = vorgabe.replace("field(default_factory=lambda: ", "").replace("field(default_factory=", "")
        vor = vor.rstrip(")") if vor.endswith(")") and "(" not in vor[:-1] else vor
        text = beschreibung.replace("|", "\\|") or "—"
        if stufe.get(name) != "A" and text != "—":
            text = f"**Tier {stufe.get(name) or '?'}.** {text}"
        teile.append(f"| `{name}` | `{typ}` | `{vor}` | {text} |\n")
    zahl = len(alle)
    teile.append(f"\n---\n\n{zahl} fields, generated from `tinysesam/config.py`.\n")
    return "".join(teile)


def main() -> int:
    neu = bauen()
    trocken = "--dry-run" in sys.argv
    alt = ZIEL.read_text(encoding="utf-8") if ZIEL.exists() else ""
    if trocken:
        if alt != neu:
            print(f"{ZIEL.name} is out of date — run `python3 scripts/_config_docs.py`",
                  file=sys.stderr)
            return 1
        return 0
    ZIEL.write_text(neu, encoding="utf-8")
    print(f"written: {ZIEL.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
