        parts.append(_section(
            f"{title}Properties of `TinySesam`",
            [f"### `{n}` — Property `{signature(p.fget)[2:].strip()}`\n\n{first_sentence(p)}\n\n"
             for n, p in properties if from_("TinySesam.properties", n) == s],
            "Read without parentheses (`auth.csrf_cookie_name`). Computed at runtime: They follow "
            "the configuration, even if `cfg` is changed after setup.\n\n"))
        parts.append(_section(
            f"{title}Constants of `TinySesam`",
            [f"### `{n}` — Constant\n\n{sentence(note.get(n, ''))}\n\n{value(getattr(TinySesam, n))}\n\n"
             for n in constants if from_("TinySesam.constants", n) == s],
            "Class attributes, read as `TinySesam.NAME` or `auth.NAME`. The value is part "
            "of the promise — the guard pins it down.\n\n"))
        # The fields of tier A are listed in full in CONFIGURATION.md; here only the exceptions.
