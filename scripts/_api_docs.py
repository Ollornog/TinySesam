    for s in ("A", "B"):
        title = f"{s} · "
        parts.append(_section(
            f"{title}Methods of `TinySesam`",
            [f"### `{n}{signature(f)}`\n\n{first_sentence(f)}\n\n"
             for n, f in methods if from_("TinySesam", n) == s]))
        # Properties (frozen since 0.20.1 like the methods): The cookie names are the
