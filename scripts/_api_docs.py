def _start(file: dict, area: str, tier: str) -> list:
    """Names of an area at one tier, sorted."""
    return sorted(n for n, e in (file.get(area) or {}).items() if isinstance(e, dict) and e.get("tier") == tier)


def _cell(text) -> str:
    return str(text).replace("|", "\\|")


def _route_table(file: dict, tier: str) -> str:
    names = _start(file, "http.routes", tier)
    lines = ["| Method | Path | Query / form parameters |\n|---|---|---|\n"]
    for n in sorted(names, key=lambda k: (k.split(" ", 1)[1], k.split(" ", 1)[0])):
        method, path = n.split(" ", 1)
        params = ", ".join(f"`{p}`" for p in file["http.routes"][n]["keys"]) or "—"
        lines.append(f"| {method} | `{_cell(path)}` | {params} |\n")
    return "".join(lines) + "\n"


def _atoms(file: dict, prefix: str, tier: str) -> list:
    return [n.split(":", 1)[1] for n in _start(file, "http.contract", tier) if n.startswith(prefix + ":")]


